	std::uint32_t load_le(const std::uint8_t *p)
	{
		return p[0] | (p[1] << 8) | (p[2] << 16) | (static_cast<std::uint32_t>(p[3]) << 24);
	}

	void store_le(std::uint8_t *p, std::uint32_t v)
	{
		for (int i = 0; i < 4; ++i, v >>= 8)
			p[i] = static_cast<std::uint8_t>(v);
	}

	void xtea_block(std::uint8_t *block, const std::uint32_t (&k)[4])
	{
		std::uint32_t v0 = load_le(block);
		std::uint32_t v1 = load_le(block + 4);
		std::uint32_t sum = 0;
		for (int i = 0; i < 32; ++i)
		{
			v0 += (((v1 << 4) ^ (v1 >> 5)) + v1) ^ (sum + k[sum & 3]);
			sum += 0x9E3779B9;
			v1 += (((v0 << 4) ^ (v0 >> 5)) + v0) ^ (sum + k[(sum >> 11) & 3]);
		}
		store_le(block, v0);
		store_le(block + 4, v1);
	}

	// Blowfish over the block's two little-endian words; EVP's BF-ECB reads them
	// big-endian, so each half is byte-reversed on the way in and out.
	bool blowfish_block(std::uint8_t *block, const std::uint8_t (&key)[24])
	{
		using cipher_ptr = std::unique_ptr<EVP_CIPHER, decltype(&::EVP_CIPHER_free)>;
		using ctx_ptr = std::unique_ptr<EVP_CIPHER_CTX, decltype(&::EVP_CIPHER_CTX_free)>;
		cipher_ptr const bf(EVP_CIPHER_fetch(nullptr, "BF-ECB", nullptr), &::EVP_CIPHER_free);
		ctx_ptr const ctx(EVP_CIPHER_CTX_new(), &::EVP_CIPHER_CTX_free);
		if (!bf || !ctx
			|| EVP_EncryptInit_ex2(ctx.get(), bf.get(), nullptr, nullptr, nullptr) != 1
			|| EVP_CIPHER_CTX_set_key_length(ctx.get(), sizeof key) != 1
			|| EVP_EncryptInit_ex2(ctx.get(), nullptr, key, nullptr, nullptr) != 1
			|| EVP_CIPHER_CTX_set_padding(ctx.get(), 0) != 1)
			return false;
		std::array<std::uint8_t, 8> in{block[3], block[2], block[1], block[0], block[7], block[6], block[5], block[4]};
		std::array<std::uint8_t, 8> out{};
		int n = 0;
		if (EVP_EncryptUpdate(ctx.get(), out.data(), &n, in.data(), static_cast<int>(in.size())) != 1 || n != 8)
			return false;
		for (int i = 0; i < 4; ++i)
		{
			block[i] = out[3 - i];
			block[4 + i] = out[7 - i];
		}
		return true;
	}
